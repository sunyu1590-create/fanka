create function public.dm_unread_counts() returns table(conversation_id uuid,unread bigint) language sql stable security invoker set search_path='' as $$
 select c.id,count(m.id) from public.dm_conversations c
 left join public.dm_reads r on r.conversation_id=c.id and r.user_id=auth.uid()
 left join public.dm_messages m on m.conversation_id=c.id and m.sender_id<>auth.uid() and m.created_at>coalesce(r.read_at,'epoch'::timestamptz)
 where auth.uid() in(c.user_a,c.user_b) group by c.id;
$$;
revoke execute on function public.dm_unread_counts() from public,anon;
grant execute on function public.dm_unread_counts() to authenticated;
